// Generates the demo escrow-issuer keypair and writes lib/issuerKeys.ts.
// Run once: npx tsx scripts/gen-issuer-keys.ts  (re-running invalidates every existing wallet)
import { writeFileSync } from 'node:fs';

const pair = await crypto.subtle.generateKey({ name: 'ECDSA', namedCurve: 'P-256' }, true, ['sign', 'verify']);
const strip = ({ kty, crv, x, y, d }: JsonWebKey) => (d ? { kty, crv, x, y, d } : { kty, crv, x, y });
const priv = strip(await crypto.subtle.exportKey('jwk', pair.privateKey));
const pub = strip(await crypto.subtle.exportKey('jwk', pair.publicKey));

writeFileSync(
  new URL('../lib/issuerKeys.ts', import.meta.url),
  `// Campus escrow issuer keypair (ECDSA P-256). Generated by scripts/gen-issuer-keys.ts.
//
// DEMO ONLY: in production the private key lives in the escrow server's HSM and never ships to a
// client; stall terminals carry only ISSUER_PUBLIC_JWK (ISO/IEC 27001 key custody). It is bundled
// here so the hackathon prototype can simulate the online pre-funding phase in the browser.

export const ISSUER_PRIVATE_JWK: JsonWebKey = ${JSON.stringify(priv, null, 2)};

export const ISSUER_PUBLIC_JWK: JsonWebKey = ${JSON.stringify(pub, null, 2)};
`,
);
console.log('Wrote lib/issuerKeys.ts');
